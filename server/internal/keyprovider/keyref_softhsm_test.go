// TestConfiguredKeyURISoftHSM is the acceptance test for Task 206: a key
// reference exactly as it would be written in the config — a full RFC 7512
// URI — must locate and use the right key on a real token, through the same
// KeyRefFor/KeySpecFor path every configured key now goes through.
//
// It covers the three things a URI buys over a bare CKA_LABEL: addressing by
// CKA_ID, addressing by token serial, and failing closed when the URI names a
// token this provider does not drive.
func TestConfiguredKeyURISoftHSM(t *testing.T) {
	module, pin, soPin := requireSoftHSM(t)

	suffix := randSuffix(t)
	tokenLabel := "cfguri-" + suffix
	keyLabel := "cfguri-key-" + suffix
	initToken(t, tokenLabel, pin, soPin)
	t.Cleanup(func() { deleteToken(tokenLabel) })

	keyPath, pub := writeECKey(t)
	importKeyWithID(t, keyPath, tokenLabel, keyLabel, "c0ffee", pin)

	p, err := NewPKCS11Provider(PKCS11Settings{ModulePath: module, Pin: pin, TokenLabel: tokenLabel})
	if err != nil {
		t.Fatalf("NewPKCS11Provider: %v", err)
	}
	t.Cleanup(func() { _ = p.Close() })

	ctx := context.Background()
	// Force the pool up so the token's real identity (serial, slot) is known,
	// which is what makes a pin exact rather than merely unfalsified.
	if err := p.Ping(ctx); err != nil {
		t.Fatalf("Ping: %v", err)
	}
	identity, ok := p.tokenIdentity()
	if !ok || identity.Serial == "" {
		t.Fatalf("token identity unavailable: %+v", identity)
	}

	// Every form a config field accepts must reach the same key.
	for _, ref := range []string{
		keyLabel,
		"pkcs11:object=" + keyLabel + ";type=private",
		"pkcs11:id=%c0%ff%ee;type=private",
		"pkcs11:object=" + keyLabel + ";serial=" + identity.Serial,
		"pkcs11:id=%c0%ff%ee;token=" + tokenLabel,
	} {
		t.Run(ref, func(t *testing.T) {
			if err := signVerify(t, p, KeyRefFor(ref), pub); err != nil {
				t.Fatalf("configured reference %q did not sign: %v", ref, err)
			}
		})
	}

	// A URI pinning a different token must fail closed rather than silently
	// using the one token this provider happens to drive.
	t.Run("wrong token fails closed", func(t *testing.T) {
		ref := KeyRefFor("pkcs11:object=" + keyLabel + ";serial=not-this-device")
		_, err := p.FindKey(ctx, ref)
		if err == nil {
			t.Fatal("FindKey with a contradicting serial unexpectedly succeeded")
		}
		if !errors.Is(err, ErrTokenMismatch) {
			t.Errorf("error %v, want it to unwrap to ErrTokenMismatch", err)
		}
		if !strings.Contains(err.Error(), "serial") {
			t.Errorf("error %q does not explain the token mismatch", err)
		}
	})

	// A wrong CKA_ID stays a clean not-found, so callers can still distinguish
	// "no such key" from "wrong device".
	t.Run("wrong id is not found", func(t *testing.T) {
		if _, err := p.FindKey(ctx, KeyRefFor("pkcs11:id=%de%ad;type=private")); !errors.Is(err, ErrKeyNotFound) {
			t.Errorf("FindKey = %v, want ErrKeyNotFound", err)
		}
	})
}

// TestGenerateKeyByURISoftHSM proves the generation path honours the same
// addressing: provisioning a key named by a URI creates it under the URI's
// object label, not under a label that literally contains "pkcs11:".
func TestGenerateKeyByURISoftHSM(t *testing.T) {
	module, pin, soPin := requireSoftHSM(t)

	suffix := randSuffix(t)
	tokenLabel := "genuri-" + suffix
	initToken(t, tokenLabel, pin, soPin)
	t.Cleanup(func() { deleteToken(tokenLabel) })

	p, err := NewPKCS11Provider(PKCS11Settings{ModulePath: module, Pin: pin, TokenLabel: tokenLabel})
	if err != nil {
		t.Fatalf("NewPKCS11Provider: %v", err)
	}
	t.Cleanup(func() { _ = p.Close() })

	ctx := context.Background()
	label := "genuri-key-" + suffix
	ref := "pkcs11:object=" + label + ";type=private"

	info, err := p.GenerateKey(ctx, KeySpecFor(ref, KeyTypeECDSAP256, KeyUsageSign))
	if err != nil {
		t.Fatalf("GenerateKey by URI: %v", err)
	}
	if info.Label != label {
		t.Fatalf("generated label = %q, want %q", info.Label, label)
	}
	// The plain label finds it, proving nothing URI-shaped was written to the
	// token as a CKA_LABEL.
	if _, err := p.FindKey(ctx, KeyRef{Label: label}); err != nil {
		t.Fatalf("key generated by URI not findable by its label: %v", err)
	}
	// And the same URI resolves it back.
	if _, err := p.FindKey(ctx, KeyRefFor(ref)); err != nil {
		t.Fatalf("key generated by URI not findable by that URI: %v", err)
	}
}

// TestSlotIDAddressingSoftHSM proves slot-id addressing reaches the token layer:
// the configured slot must be the one the pool binds to, and a wrong slot must
// fail to find a token at all rather than silently picking another.
func TestSlotIDAddressingSoftHSM(t *testing.T) {
	module, pin, soPin := requireSoftHSM(t)

	suffix := randSuffix(t)
	tokenLabel := "sloturi-" + suffix
	initToken(t, tokenLabel, pin, soPin)
	t.Cleanup(func() { deleteToken(tokenLabel) })

	// Discover the slot the new token landed in.
	probe, err := NewPKCS11Provider(PKCS11Settings{ModulePath: module, Pin: pin, TokenLabel: tokenLabel})
	if err != nil {
		t.Fatalf("NewPKCS11Provider: %v", err)
	}
	if err := probe.Ping(context.Background()); err != nil {
		t.Fatalf("Ping: %v", err)
	}
	identity, ok := probe.tokenIdentity()
	if !ok {
		t.Fatal("token identity unavailable")
	}
	slot := identity.SlotID
	_ = probe.Close()

	// Addressing by slot-id alone (no label) must bind to the same token.
	bySlot, err := NewPKCS11Provider(PKCS11Settings{ModulePath: module, Pin: pin, SlotID: &slot})
	if err != nil {
		t.Fatalf("NewPKCS11Provider(slot-id): %v", err)
	}
	t.Cleanup(func() { _ = bySlot.Close() })
	if err := bySlot.Ping(context.Background()); err != nil {
		t.Fatalf("Ping via slot-id %d: %v", slot, err)
	}
	got, _ := bySlot.tokenIdentity()
	if got.Label != tokenLabel {
		t.Errorf("slot-id %d bound to token %q, want %q", slot, got.Label, tokenLabel)
	}

	// A slot that holds no token must fail with a message naming the selector.
	absent := slot + 9999
	bad, err := NewPKCS11Provider(PKCS11Settings{ModulePath: module, Pin: pin, SlotID: &absent})
	if err != nil {
		t.Fatalf("NewPKCS11Provider(absent slot): %v", err)
	}
	t.Cleanup(func() { _ = bad.Close() })
	err = bad.Ping(context.Background())
	if err == nil {
		t.Fatal("a nonexistent slot-id unexpectedly produced a working pool")
	}
	if !strings.Contains(err.Error(), "slot-id") {
		t.Errorf("error %q does not name the slot-id selector", err)
	}
}
