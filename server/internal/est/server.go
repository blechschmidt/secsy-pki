// Package est implements the EST (Enrollment over Secure Transport, RFC 7030)
// server operations on top of the HSM-backed ca.Manager issuance layer:
//
//   - GET  /.well-known/est/cacerts       — CA certificate distribution
//   - POST /.well-known/est/simpleenroll  — initial enrollment
//   - POST /.well-known/est/simplereenroll — renewal
//   - POST /.well-known/est/serverkeygen  — server-side key generation (optional)
//
// Clients authenticate with HTTP Basic credentials (operator-provisioned, the
// EST analogue of an RBAC grant) or a TLS client certificate previously issued
// by this CA. Every leaf is signed through the shared ca.Manager, so the CA key
// never leaves its provider.
package est

